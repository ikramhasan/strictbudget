import { index, jsonb, pgTable, text, timestamp } from "drizzle-orm/pg-core";

export const AUDIT_OPS = ["insert", "update", "delete"] as const;
export type AuditOp = (typeof AUDIT_OPS)[number];

/**
 * The budget's change history: one row per inserted, updated or deleted row of a
 * budget's data, written by the `strictbudget_audit_row` trigger in the same transaction as the change
 * (migration 0038). Append-only. Rows whose budget is deleted go with it. Changes that only touch
 * bookkeeping columns (updated_at, version, last_used_at…) aren't logged.
 *
 * The actor, client and request come from the transaction's `strictbudget.*` settings
 * (`apps/api/src/lib/audit-context.ts`); a change made outside a request (a scheduled transaction
 * entered on read, a script) has no actor. Ids aren't foreign keys: the log outlives the rows it
 * describes, and a deleted user's id is cleared from it with their account.
 */
export const auditEvent = pgTable(
  "audit_event",
  {
    /** UUIDv7, generated by the trigger (`strictbudget_uuid_v7()`). */
    id: text().primaryKey(),
    budgetId: text().notNull(),
    /** Who made the change; null for changes outside a request or once their user is deleted. */
    actorUserId: text(),
    /** The agent (`connected_agent`) that made it for that user; null for the user's own changes. */
    actorAgentId: text(),
    /** The browser tab that made it (the `X-Client-Id` header), so its own events can be skipped. */
    clientId: text(),
    requestId: text(),
    /** Why a change without an actor happened, e.g. "scheduled" for an entered occurrence. */
    source: text(),
    tableName: text().notNull(),
    rowId: text().notNull(),
    op: text({ enum: AUDIT_OPS }).notNull(),
    /** The row before the change (null for an insert), as `to_jsonb`; secrets left out. */
    before: jsonb(),
    /** The row after the change (null for a delete). */
    after: jsonb(),
    createdAt: timestamp({ withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("audit_event_budget_created_idx").on(t.budgetId, t.createdAt),
    index("audit_event_row_idx").on(t.tableName, t.rowId),
  ],
);
